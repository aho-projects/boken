#!/usr/bin/env node
/**
 * Build WordPress paste-ready snippets from the existing boken/*.html files.
 *
 * Strategy:
 *   - Read the original opplegg HTML (it already has the full visual content)
 *   - Strip the <html>, <head>, kr-header, kr-footer (WP provides its own chrome)
 *   - Replace the SVG placeholder map (naturfag) with an iframe to /embed/naturfag-map
 *   - Add an Ut og titte radius map iframe to ut-og-titte.html
 *   - Prepend the iframe-resize listener
 *   - Output to wp-snippets/
 *
 * After deploying boken-live to Vercel, just find-and-replace BOKEN_HOST in the
 * snippet files with the real URL.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");
const sourceDir = resolve(projectRoot, "..", "boken"); // ../boken
const outDir = resolve(projectRoot, "wp-snippets");
mkdirSync(outDir, { recursive: true });

const BOKEN_HOST_PLACEHOLDER = "https://boken-kappa.vercel.app";

const RESIZE_SCRIPT = `<script>
(function () {
  var BOKEN_HOST = ${JSON.stringify(BOKEN_HOST_PLACEHOLDER)};
  window.addEventListener('message', function (e) {
    if (!e || !e.data || e.data.type !== 'boken-resize') return;
    document.querySelectorAll('iframe[src^="' + BOKEN_HOST + '"]').forEach(function (f) {
      if (f.contentWindow === e.source) {
        f.style.height = (e.data.height + 4) + 'px';
      }
    });
  });
})();
</script>`;

const PRE_BANNER = `<!--
  ============================================================
  Boken — WordPress paste snippet
  Generated by scripts/build-wp-snippets.mjs.
  Before pasting:
    - Replace ${BOKEN_HOST_PLACEHOLDER} with your real Vercel URL
    - Replace WP_MEDIA_BASE/ with your WP media path (e.g. https://kasserommet.no/wp-content/uploads/2026/05/)
  ============================================================
-->\n`;

/** Extract everything inside <body>…</body>, dropping kr-header/footer. */
function extractBody(html) {
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i);
  if (!bodyMatch) throw new Error("No <body> found");
  let body = bodyMatch[1];

  // Drop the kr-header (paper-warm header bar with logo + nav)
  body = body.replace(/<header class="kr-header"[\s\S]*?<\/header>/i, "");
  // Drop the kr-footer (dark footer with brand + links)
  body = body.replace(/<footer class="kr-footer"[\s\S]*?<\/footer>/i, "");
  // Drop the WP shell (wp-header/wp-footer) if present
  body = body.replace(/<header class="wp-header"[\s\S]*?<\/header>/i, "");
  body = body.replace(/<footer class="wp-footer"[\s\S]*?<\/footer>/i, "");

  return body.trim();
}

/** Extract the <style> block(s) inside <head>. */
function extractStyles(html) {
  const headMatch = html.match(/<head[^>]*>([\s\S]*?)<\/head>/i);
  if (!headMatch) return "";
  const head = headMatch[1];
  // Grab inline <style> blocks but keep any @import font link
  const styles = [];
  for (const m of head.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)) {
    styles.push(`<style>${m[1]}</style>`);
  }
  // Pick up font link if present
  const fontLink = head.match(/<link[^>]*googleapis[^>]*>/i)?.[0] ?? "";
  return (fontLink ? fontLink + "\n" : "") + styles.join("\n");
}

/** Read the shared styles.css and inline it as a <style> block.  */
function readSharedStyles() {
  const cssPath = resolve(sourceDir, "styles.css");
  if (!existsSync(cssPath)) return "";
  return `<style>\n${readFileSync(cssPath, "utf8")}\n</style>`;
}

/** Replace the naturfag-ute placeholder map (form + SVG) with an iframe. */
function injectNaturfagMap(body) {
  // Match the entire <section class="area-section"> through its closing tag
  return body.replace(
    /<section class="area-section"[\s\S]*?<\/section>/i,
    `<section class="area-section">
  <h2>Hvor i nærmiljøet?</h2>
  <p class="sub">Slå opp skolen din eller bruk posisjonen din, så viser vi forslag til parker, skog og vann dere kan dra ut til. Data fra OpenStreetMap.</p>
  <iframe
    src="${BOKEN_HOST_PLACEHOLDER}/embed/naturfag-map"
    title="Kart over nærmiljø"
    style="width:100%; min-height:760px; border:0; background:transparent;"
    loading="lazy"
    scrolling="no"
  ></iframe>
</section>`,
  );
}

/** Add the Ut og titte radius map + checklist iframe to ut-og-titte.html. */
function injectUtOgTitteMap(body) {
  // Insert after the description card (or before the continue row)
  const iframeBlock = `
<section class="area-section">
  <h2>Hvor får dere lov til å gå?</h2>
  <p class="sub">Trykk «Finn meg» — kartet tegner en sirkel rundt dere. Det er deres område for denne timen. Bruk listene under til å huke av det dere finner. Tegn det fineste i boka.</p>
  <iframe
    src="${BOKEN_HOST_PLACEHOLDER}/embed/ut-og-titte"
    title="Radius rundt deg + sjekkliste"
    style="width:100%; min-height:1100px; border:0; background:transparent;"
    loading="lazy"
    scrolling="no"
  ></iframe>
</section>
`;
  // Try to insert before the .continue row
  if (/<div class="continue"/.test(body)) {
    return body.replace(/(<div class="continue")/i, `${iframeBlock}\n$1`);
  }
  // Fallback: append before </main>
  return body.replace(/<\/main>/i, `${iframeBlock}\n</main>`);
}

/** Replace the page-bottom feedback form with an iframe (homepage only). */
function injectFeedbackForm(body) {
  return body.replace(
    /<section class="feedback-section"[\s\S]*?<\/section>/i,
    `<section class="feedback-section" id="feedback" style="background: var(--ink); color: #fff; padding: 100px 56px;">
  <div class="feedback-inner" style="max-width: 1280px; margin: 0 auto; display: grid; grid-template-columns: 1fr 1.2fr; gap: 64px; align-items: start;">
    <div class="intro">
      <div class="hero-eyebrow" style="color:var(--orange);">Til læreren</div>
      <h2>Del erfaringene dine.</h2>
      <p>Brukte du et av oppleggene i klassen? Vi vil veldig gjerne høre hvordan det gikk — og se hva elevene laget.</p>
    </div>
    <iframe
      src="${BOKEN_HOST_PLACEHOLDER}/embed/feedback"
      title="Tilbakemelding fra lærer"
      style="width:100%; min-height:900px; border:0; background:transparent;"
      loading="lazy"
      scrolling="no"
    ></iframe>
  </div>
</section>`,
  );
}

/** Replace the per-opplegg <eksempler-students-section> with an iframe. */
function makeExamplesInjector(oppleggId) {
  return function injectExamples(body) {
    const iframeBlock = `<section class="eksempler-students-section">
  <iframe
    src="${BOKEN_HOST_PLACEHOLDER}/embed/examples?opplegg=${oppleggId}"
    title="Eksempler fra elever — ${oppleggId}"
    style="width:100%; min-height:520px; border:0; background:transparent;"
    loading="lazy"
    scrolling="no"
  ></iframe>
</section>`;
    if (/<section class="eksempler-students-section"/i.test(body)) {
      return body.replace(
        /<section class="eksempler-students-section"[\s\S]*?<\/section>/i,
        iframeBlock,
      );
    }
    // Fallback: insert before the continue row
    if (/<div class="continue"/.test(body)) {
      return body.replace(/(<div class="continue")/i, `${iframeBlock}\n$1`);
    }
    return body;
  };
}

/** Replace the homepage examples grid with the cross-section iframe. */
function injectHomeExamples(body) {
  return body.replace(
    /<section class="home-eksempler-section"[\s\S]*?<\/section>/i,
    `<section class="home-eksempler-section">
  <div class="home-eksempler-inner">
    <iframe
      src="${BOKEN_HOST_PLACEHOLDER}/embed/examples"
      title="Eksempler fra lærere"
      style="width:100%; min-height:560px; border:0; background:transparent;"
      loading="lazy"
      scrolling="no"
    ></iframe>
  </div>
</section>`,
  );
}

/** Make a grupper.html snippet from scratch (no source file for this page). */
function buildGrupperSnippet(sharedStyles) {
  return `${PRE_BANNER}${sharedStyles}
${RESIZE_SCRIPT}
<main class="opplegg-page">
  <div class="crumb"><a href="/">Hjem</a> &nbsp;/&nbsp; Grupper</div>
  <h1 class="opplegg-title">Lag grupper</h1>
  <div class="opplegg-sub">— stokk klassen i tilfeldige grupper på 2–5 elever —</div>
  <section class="desc-card yellow" style="margin-bottom: 28px;">
    <h2>Slik bruker du det</h2>
    <p>
      Lim inn klasselista — ett navn per linje, eller bare skriv et tall som «24». Velg gruppestørrelse, og trykk «Stokk!».
      Klikk en elev for å låse dem til gruppa når du stokker på nytt. Skriv ut eller kopier resultatet til Teams / e-post.
    </p>
  </section>
  <iframe
    src="${BOKEN_HOST_PLACEHOLDER}/embed/grupper"
    title="Lag grupper"
    style="width:100%; min-height:1100px; border:0; background:transparent;"
    loading="lazy"
    scrolling="no"
  ></iframe>
</main>
`;
}

const tasks = [
  // Homepage: feedback form iframe at bottom + cross-section examples gallery
  { src: "index.html", out: "home.html",
    transforms: [injectFeedbackForm, injectHomeExamples] },
  // Naturfag: live map + naturfag-filtered examples
  { src: "naturfag-ute.html", out: "naturfag-ute.html",
    transforms: [injectNaturfagMap, makeExamplesInjector("naturfag")] },
  // Ut og titte: radius map + filtered examples
  { src: "ut-og-titte.html", out: "ut-og-titte.html",
    transforms: [injectUtOgTitteMap, makeExamplesInjector("ut-og-titte")] },
  // Pure static opplegg pages — just swap the examples grid for the iframe
  { src: "sketchnoting.html", out: "sketchnoting.html",
    transforms: [makeExamplesInjector("sketchnoting")] },
  { src: "isberg.html", out: "isberg.html",
    transforms: [makeExamplesInjector("isberg")] },
  { src: "bytte-perspektiv.html", out: "bytte-perspektiv.html",
    transforms: [makeExamplesInjector("bytte-perspektiv")] },
  { src: "hjemmelagde-kilden.html", out: "hjemmelagde-kilden.html",
    transforms: [makeExamplesInjector("hjemmelagde-kilden")] },
  { src: "hvordan-lage-boka.html", out: "hvordan-lage-boka.html",
    transforms: [] },
];

const sharedStyles = readSharedStyles();

for (const t of tasks) {
  const srcPath = resolve(sourceDir, t.src);
  if (!existsSync(srcPath)) {
    console.warn(" skipped (not found):", t.src);
    continue;
  }
  const raw = readFileSync(srcPath, "utf8");
  let body = extractBody(raw);
  const pageStyles = extractStyles(raw);
  for (const fn of t.transforms) body = fn(body);

  const out = `${PRE_BANNER}${sharedStyles}\n${pageStyles}\n${RESIZE_SCRIPT}\n${body}\n`;
  writeFileSync(resolve(outDir, t.out), out);
  console.log(" wrote", t.out);
}

